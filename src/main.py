Positive = Annotated[float, Field(gt=0, allow_inf_nan=False)]

class WineData(BaseModel):
    model_config = ConfigDict(extra="forbid", json_schema_extra={"example": {
        "alcohol": 13.2, "malic_acid": 1.78, "ash": 2.14,
        "alcalinity_of_ash": 11.2, "magnesium": 100, "total_phenols": 2.65,
        "flavanoids": 2.76, "nonflavanoid_phenols": 0.26,
        "proanthocyanins": 1.28, "color_intensity": 4.38, "hue": 1.05,
        "od280_od315_of_diluted_wines": 3.4, "proline": 1050}})
    alcohol: Positive
    malic_acid: Positive
    ash: Positive
    alcalinity_of_ash: Positive
    magnesium: Positive
    total_phenols: Positive
    flavanoids: Positive
    nonflavanoid_phenols: Positive
    proanthocyanins: Positive
    color_intensity: Positive
    hue: Positive
    od280_od315_of_diluted_wines: Positive
    proline: Positive

class WineResponse(BaseModel):
    predicted_class: int
    cultivar: str
    probabilities: dict[str, float]
    model: str
    prediction_id: int

@asynccontextmanager
async def lifespan(app: FastAPI):
    # Load only the trusted artifact generated by this project's training script.
    app.state.bundle = joblib.load(MODEL_PATH)
    store.initialize()
    app.state.request_count = 0
    app.state.error_count = 0
    yield

app = FastAPI(title="Wine Cultivar Prediction API", version="1.0.0", lifespan=lifespan,
              description="MLOps FastAPI lab: predict one of three wine cultivars from chemical measurements.")

@app.get("/", tags=["Health"])
def health():
    return {"status": "healthy", "model": "wine-random-forest-v1"}

@app.get("/model-info", tags=["Model"])
def model_info():
    return app.state.bundle["metrics"]

def get_bundle(request: Request):
    """Dependency injection supplies the one model loaded at startup."""
    return request.app.state.bundle

@app.middleware("http")
async def observe(request: Request, call_next):
    started = time.perf_counter()
    request.state.request_id = str(uuid.uuid4())
    response = await call_next(request)
    app.state.request_count += 1
    if response.status_code >= 400:
        app.state.error_count += 1
    response.headers["X-Request-ID"] = request.state.request_id
    response.headers["X-Process-Time-Ms"] = f"{(time.perf_counter()-started)*1000:.3f}"
    return response

@app.exception_handler(HTTPException)
async def http_error(request: Request, exc: HTTPException):
    return JSONResponse(status_code=exc.status_code, content={
        "error": exc.detail, "request_id": request.state.request_id})

@app.exception_handler(RequestValidationError)
async def validation_error(request: Request, exc: RequestValidationError):
    return JSONResponse(status_code=422, content=jsonable_encoder({
        "error": "Request validation failed", "detail": exc.errors(),
        "request_id": request.state.request_id}))

def infer(data: WineData, bundle):
    row = [[getattr(data, name) for name in FEATURES]]
    predicted = int(bundle["model"].predict(row)[0])
    probabilities = bundle["model"].predict_proba(row)[0]
    result = {"predicted_class": predicted, "cultivar": bundle["classes"][predicted],
              "probabilities": dict(zip(bundle["classes"], probabilities.tolist())),
              "model": "wine-random-forest-v1"}
    result["prediction_id"] = store.record(data.model_dump(), result)
    return result

@app.post("/predict", response_model=WineResponse, tags=["Prediction"])
def predict(data: WineData, bundle=Depends(get_bundle)):
    """Predict a cultivar and save the input and result in SQLite."""
    return infer(data, bundle)

class BatchRequest(BaseModel):
    samples: list[WineData] = Field(min_length=1, max_length=100)

class BatchResponse(BaseModel):
    count: int
    predictions: list[WineResponse]

@app.post("/predict/batch", response_model=BatchResponse, tags=["Prediction"])
def batch(data: BatchRequest, bundle=Depends(get_bundle)):
    """Validate the entire batch before saving any predictions (1-100 samples)."""
    return {"count": len(data.samples), "predictions": [infer(x, bundle) for x in data.samples]}

@app.post("/predict/csv", response_model=BatchResponse, tags=["Prediction"])
def csv_predict(file: UploadFile = File(...), bundle=Depends(get_bundle)):
    """Upload UTF-8 CSV with exactly the 13 named feature columns; maximum 100 rows / 1 MB."""
    content = file.file.read(1_000_001)
    if len(content) > 1_000_000:
        raise HTTPException(413, "CSV exceeds 1 MB")
    try:
        reader = csv.DictReader(io.StringIO(content.decode("utf-8-sig")))
        if reader.fieldnames is None or len(reader.fieldnames) != len(FEATURES) or set(reader.fieldnames) != set(FEATURES):
            raise HTTPException(422, "CSV headers must match the 13 feature names exactly")
        rows = []
        for number, row in enumerate(reader, 1):
            if number > 100:
                raise HTTPException(422, "CSV exceeds 100 rows")
            rows.append(WineData.model_validate(row))
        if not rows:
            raise HTTPException(422, "CSV contains no samples")
    except (UnicodeDecodeError, ValueError, csv.Error) as exc:
        raise HTTPException(422, "CSV must contain UTF-8 text and valid positive measurements") from exc
    return {"count": len(rows), "predictions": [infer(x, bundle) for x in rows]}

@app.get("/predictions", tags=["History"])
def history(cultivar: str | None = Query(None, pattern=r"^class_[012]$"),
            limit: int = Query(10, ge=1, le=100), offset: int = Query(0, ge=0)):
    """Filter saved results by cultivar and page through newest first."""
    where = " WHERE cultivar=?" if cultivar else ""
    args = [cultivar] if cultivar else []
    with store.connect() as db:
        total = db.execute("SELECT COUNT(*) FROM predictions"+where, args).fetchone()[0]
        rows = db.execute("SELECT * FROM predictions"+where+" ORDER BY id DESC LIMIT ? OFFSET ?",
                          args+[limit, offset]).fetchall()
    return {"total": total, "limit": limit, "offset": offset,
            "items": [store.unpack(row) for row in rows]}

def find_prediction(prediction_id):
    with store.connect() as db:
        row = db.execute("SELECT * FROM predictions WHERE id=?", (prediction_id,)).fetchone()
    if row is None:
        raise HTTPException(404, "Prediction not found")
    return store.unpack(row)

@app.get("/predictions/{prediction_id}", tags=["History"])
def get_prediction(prediction_id: int):
    return find_prediction(prediction_id)

class Annotation(BaseModel):
    model_config = ConfigDict(extra="forbid")
    note: str = Field(max_length=500)

@app.patch("/predictions/{prediction_id}", tags=["History"])
def annotate(prediction_id: int, annotation: Annotation):
    find_prediction(prediction_id)
    with store.connect() as db:
        db.execute("UPDATE predictions SET note=? WHERE id=?", (annotation.note, prediction_id))
    return find_prediction(prediction_id)

@app.delete("/predictions/{prediction_id}", status_code=204, tags=["History"])
def delete_prediction(prediction_id: int):
    with store.connect() as db:
        cursor = db.execute("DELETE FROM predictions WHERE id=?", (prediction_id,))
    if cursor.rowcount == 0:
        raise HTTPException(404, "Prediction not found")

def run_job(job_id, samples, bundle):
    try:
        with store.connect() as db:
            db.execute("UPDATE jobs SET status='running' WHERE id=?", (job_id,))
        results = [infer(sample, bundle) for sample in samples]
        with store.connect() as db:
            db.execute("UPDATE jobs SET status='completed',result=? WHERE id=?",
                       (json.dumps(results), job_id))
    except Exception:
        with store.connect() as db:
            db.execute("UPDATE jobs SET status='failed',error='Prediction job failed' WHERE id=?", (job_id,))

@app.post("/jobs", status_code=202, tags=["Background jobs"])
def create_job(data: BatchRequest, tasks: BackgroundTasks, bundle=Depends(get_bundle)):
    job_id = str(uuid.uuid4())
    with store.connect() as db:
        db.execute("INSERT INTO jobs(id,status) VALUES (?,'queued')", (job_id,))
    tasks.add_task(run_job, job_id, data.samples, bundle)
    return {"job_id": job_id, "status": "queued", "status_url": f"/jobs/{job_id}"}

@app.get("/jobs/{job_id}", tags=["Background jobs"])
def job_status(job_id: str):
    with store.connect() as db:
        row = db.execute("SELECT * FROM jobs WHERE id=?", (job_id,)).fetchone()
    if row is None:
        raise HTTPException(404, "Job not found")
    result = dict(row)
    result["result"] = json.loads(result["result"]) if result["result"] else None
    return result

@app.get("/metrics", tags=["Monitoring"])
def metrics():
    with store.connect() as db:
        total = db.execute("SELECT COUNT(*) FROM predictions").fetchone()[0]
    return {"requests_this_process": app.state.request_count,
            "errors_this_process": app.state.error_count, "saved_predictions": total}
